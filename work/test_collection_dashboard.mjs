import assert from 'node:assert/strict';
import {renderCollectionDashboard} from '../job_collector_ui/public/collection-dashboard.js';
const format={number:n=>Number(n).toLocaleString('en-US'),escapeHtml:s=>String(s).replaceAll('<','&lt;')};
const task={status:'running',currentStage:'public',platforms:['shixiseng','zhaopin'],targetRows:20000,metrics:{candidates:5837,publicRows:5837,zhaopinRows:0,hasFinalResult:false,liveCollection:{platformCounts:{shixiseng:5350},details:[{platform:'shixiseng',discovered:10044,processed:5622,successful:5620,failed:2}]}}};
let html=renderCollectionDashboard(task,format);
assert.match(html,/5,837/);assert.match(html,/29%/);assert.match(html,/56%/);
assert.match(html,/待导出/);assert.doesNotMatch(html,/鱼泡直聘|BOSS直聘/);
assert.match(html,/成功 <b>5,620/);assert.match(html,/has-errors/);
assert.doesNotMatch(html,/实习僧详情处理|collection-detail-card/);
assert.match(html,/<details class="collection-channel-details"/);
assert.doesNotMatch(html,/<details[^>]*\sopen[\s>]/);
assert.match(html,/<td>实习僧<\/td><td>5,350 条/);
assert.match(html,/<td>智联招聘<\/td><td>0 条<\/td><td>暂未提供/);
assert.match(html,/aria-valuenow="29"/);
assert.equal((html.match(/<li class="collection-step /g)||[]).length,2);
assert.match(html,/多平台采集/);assert.doesNotMatch(html,/智联采集|<div>合并去重/);
html=renderCollectionDashboard({...task,currentStage:'zhaopin'},format);
assert.match(html, /collection-step active"><span>1<\/span><div>多平台采集/);
assert.match(html,/自动归集去重/);
html=renderCollectionDashboard({...task,currentStage:'finalize',collectionIssues:[{stage:'public'}]},format);
assert.match(html,/部分受阻/);assert.match(html,/collection-step done/);
assert.match(html,/collection-step active"><span>2<\/span><div>导出交付/);
html=renderCollectionDashboard({...task,status:'completed',currentStage:'',metrics:{...task.metrics,hasFinalResult:true,finalRows:20001,duplicatesRemoved:100}},format);
assert.match(html,/交付完成度/);assert.match(html,/20,001 条/);assert.match(html,/100%/);
assert.match(html,/已完成/);
console.log('PASS: dashboard counts, stages, unused channels, failures, capped progress and candidate/delivery separation');
