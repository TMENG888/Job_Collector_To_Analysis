import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {synchronizePublicKeywords,retainedChannelErrors} from './task_collection_config.mjs';
const dir=await fs.mkdtemp(path.join(os.tmpdir(),'task-keywords-'));
const publicConfigPath=path.join(dir,'config.json');
const config={task_id:'task',keywords:['新媒体运营'],request:{concurrency:2},platforms:{jobonline:{enabled:true,maxPages:10}}};
await fs.writeFile(publicConfigPath,JSON.stringify(config));
const task={id:'task',primaryKeyword:'新媒体运营',keywords:['新媒体运营','短视频运营','公众号运营','短视频运营'],publicConfigPath};
assert.equal((await synchronizePublicKeywords(task)).changed,true);
const updated=JSON.parse(await fs.readFile(publicConfigPath,'utf8'));
assert.deepEqual(updated.keywords,['新媒体运营','短视频运营','公众号运营']);
assert.deepEqual(updated.request,config.request);
assert.deepEqual(updated.platforms,config.platforms);
assert.equal((await synchronizePublicKeywords(task)).changed,false);
await assert.rejects(synchronizePublicKeywords({...task,id:'foreign'}),/不属于/);
const error={stopChannel:true,code:'layout_changed',keyword:'新媒体运营'};
const manifest={task_id:'task',platforms:{jobonline:{errors:[error]}}};
assert.deepEqual(retainedChannelErrors(manifest,'task','jobonline','skip'),[error]);
assert.deepEqual(retainedChannelErrors(manifest,'foreign','jobonline','skip'),[]);
assert.deepEqual(retainedChannelErrors(manifest,'task','jobonline','wait'),[]);
assert.deepEqual(retainedChannelErrors(manifest,'task','iguopin','skip'),[]);
// Execute the real collector against a retained blocked-channel fixture: no
// platform request is needed, and partial data must survive exit code 44.
const fixture=path.join(dir,'retained');
await fs.mkdir(fixture);
const fixtureConfig=path.join(dir,'retained-config.json');
await fs.writeFile(fixtureConfig,JSON.stringify({task_id:'task',keywords:['新媒体运营'],platforms:{jobonline:{enabled:true,cities:[{name:'全国'}]}}}));
await fs.writeFile(path.join(fixture,'采集清单.json'),JSON.stringify(manifest));
await fs.writeFile(path.join(fixture,'jobonline_标准化数据.csv'),'platform,query_keyword,job_id\n就业在线,新媒体运营,retained-1');
const child=spawn(process.execPath,[fileURLToPath(new URL('./collect_public_job_platforms.mjs',import.meta.url)),fixtureConfig,fixture],{env:{...process.env,JOB_COLLECTOR_BLOCKED_POLICY:'skip'},windowsHide:true});
let logs='';child.stdout.on('data',data=>logs+=data);child.stderr.on('data',data=>logs+=data);
const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('close',resolve);});
assert.equal(code,44,logs);
assert.match(logs,/本轮跳过/);
const retained=JSON.parse(await fs.readFile(path.join(fixture,'采集清单.json'),'utf8'));
assert.equal(retained.total_rows,1);
assert.equal(retained.platforms.jobonline.rows,1);
console.log('PASS: full keyword launch synchronization; preserve limits; task isolation; skip previously blocked channel only in pipeline');
