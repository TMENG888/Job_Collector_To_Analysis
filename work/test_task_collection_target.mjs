import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {validJobRecord,otherChannelValidCount} from './task_collection_target.mjs';
const good={platform:'就业在线',job_id:'1',job_name:'数据分析师',company_name:'测试公司',city:'北京',job_url:'https://www.jobonline.cn/positionDetail?id=1',job_description:'负责数据分析、业务指标建设和可视化报表开发，并与业务团队协作。'};
assert.ok(validJobRecord(good));
for(const field of ['job_id','job_name','company_name','city','job_url','job_description'])assert.equal(validJobRecord({...good,[field]:''}),false);
for(const description of ['负责数据','<html>请按住滑块访问验证</html>','Protected by Tencent Cloud EdgeOne'])assert.equal(validJobRecord({...good,job_description:description}),false);
const dir=await fs.mkdtemp(path.join(os.tmpdir(),'task-valid-target-'));
await fs.writeFile(path.join(dir,'任务归属.json'),JSON.stringify({task_id:'fixture-task'}));
const headers=Object.keys(good),rows=[good,{...good,job_id:'2',city:''},{...good,job_id:'3'},{...good,job_id:'4'}];
await fs.writeFile(path.join(dir,'jobonline_标准化数据.csv'),headers.join(',')+'\n'+rows.map(row=>headers.map(key=>row[key]).join(',')).join('\n'));
assert.equal(await otherChannelValidCount(dir,'zhaopin','fixture-task'),3);
await assert.rejects(otherChannelValidCount(dir,'zhaopin','wrong-task'),/归属不符/);
const profile=path.join(dir,'profile.json');await fs.writeFile(profile,JSON.stringify({task_id:'fixture-task',label:'数据分析',strict_valid_rows:true,trim_to_target:true}));
const python=process.env.JOB_UI_PYTHON||'python';
const result=spawnSync(python,['work/finalize_configurable_dataset.py',dir,profile,'2'],{encoding:'utf8'});
assert.equal(result.status,0,result.stderr);
const quality=JSON.parse(await fs.readFile(path.join(dir,'数据质量报告.json'),'utf8'));
assert.equal(quality.output_rows,2);assert.equal(quality.validity_excluded_rows,1);assert.equal(quality.trimmed_rows,1);assert.equal(quality.target_reached,true);assert.equal(quality.task_id,'fixture-task');
const insufficient=spawnSync(python,['work/finalize_configurable_dataset.py',dir,profile,'5'],{encoding:'utf8'});
assert.equal(insufficient.status,0,insufficient.stderr);
const short=JSON.parse(await fs.readFile(path.join(dir,'数据质量报告.json'),'utf8'));
assert.equal(short.output_rows,3);assert.equal(short.target_reached,false);assert.equal(short.validity_excluded_rows,1);
console.log(JSON.stringify({ok:true,checks:['strict required fields','verification exclusion','same-task budget only','validity gate parity','exact target trim'],testDir:dir}));
