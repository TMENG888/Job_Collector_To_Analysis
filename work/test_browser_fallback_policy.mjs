import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {browserFallbackAllowed,assertBrowserAccess,withBrowserStep,rateKey,recordBrowserDenial} from './browser_fallback_policy.mjs';
import {HYBRID_MODE,collectionTransportPolicy,collectionPolicyFor} from './channel_acquisition.mjs';
import {collectionChannelAvailable} from './channel_availability.mjs';

const dir=await fs.mkdtemp(path.join(os.tmpdir(),'browser-fallback-policy-'));
const allows=(platform,errors=[],httpReady=true,mode=HYBRID_MODE)=>browserFallbackAllowed({platform,errors,httpReady,mode});
assert.equal(allows('zhaopin',[{code:'invalid_response'}]),true);
assert.equal(allows('jobonline',[],false),true);
assert.equal(allows('jobonline',[{code:'unknown_business_error'}],false),false);
assert.equal(allows('jobonline',[],false,collectionTransportPolicy.mode),false);
assert.equal(allows('zhaopin'),false,'success/empty results never trigger transport switching');
for(const code of ['verification_required','access_blocked','login_required','origin_cooldown','pagination_stalled','RESOURCE_PRESSURE','OUTPUT_LOCKED','TASK_OUTPUT_OWNERSHIP',42,43])assert.equal(allows('zhaopin',[{code}]),false,String(code));
for(const platform of ['boss','yupao','shixiseng','unknown'])assert.equal(allows(platform,[],false),false);
assert.equal(collectionChannelAvailable('job51'),false);
assert.equal(collectionChannelAvailable('job51',{transportMode:HYBRID_MODE}),true);
assert.equal(collectionChannelAvailable('boss',{transportMode:HYBRID_MODE}),false);
assert.equal(collectionPolicyFor({}).browserAutomation,false);
assert.equal(collectionPolicyFor({transportMode:HYBRID_MODE}).maxBrowserWorkers,1);

const file=path.join(dir,rateKey('https://api.jobonline.cn')+'.json');
let now=100000,calls=0,waited=0;
await fs.writeFile(file,JSON.stringify({lastStartedAt:99000}));
const opts={now:()=>now,jitterMs:0,wait:async ms=>{waited+=ms;now+=ms;}};
await withBrowserStep('jobonline',dir,async()=>{calls++;},opts);
assert.equal(waited,3000,'RPA uses previous HTTP start time');
await withBrowserStep('jobonline',dir,async()=>{calls++;},opts);
assert.equal(waited,7000,'minimum 4-second pacing');assert.equal(calls,2);
const alias=path.join(dir,rateKey('https://www.jobonline.cn')+'.json');
await fs.writeFile(alias,JSON.stringify({cooldownUntil:now+1000}));
await assert.rejects(withBrowserStep('jobonline',dir,async()=>{calls++;},opts),{code:'origin_cooldown'});
assert.equal(calls,2,'no request during alias cooldown');
await fs.writeFile(alias,JSON.stringify({status:'verification_required',cooldownUntil:1}));
await assert.rejects(assertBrowserAccess('jobonline',dir,{now}),{code:'waiting_human'});
await fs.writeFile(alias,JSON.stringify({status:'challenge',cooldownUntil:1}));
await assert.rejects(assertBrowserAccess('jobonline',dir,{now}),{code:'waiting_human'});
await recordBrowserDenial('job51',dir,'access_blocked');
const denial=JSON.parse(await fs.readFile(path.join(dir,rateKey('https://we.51job.com')+'.json'),'utf8'));
assert.equal(denial.status,'access_blocked');assert.ok(denial.cooldownUntil>Date.now());
console.log('PASS browser fallback policy: opt-in, safe-error allowlist, no denial/exhaustion fallback, shared HTTP pacing, alias cooldown and sticky verification.');
