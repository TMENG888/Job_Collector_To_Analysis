import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {liveCollectionMetrics} from './live_collection_metrics.mjs';
import {mergeLiveProgress,collectionProgress} from '../job_collector_ui/public/collection-progress.js';
const outputDir = await fs.mkdtemp(path.join(os.tmpdir(),'job-live-metrics-'));
const task = {id:'test-task',outputDir,targetRows:20000,status:'running',metrics:{publicRows:0,candidates:0,finalRows:0,hasFinalResult:false}};
const dir=path.join(outputDir,'断点数据');
await fs.mkdir(dir);
const write = (name,data)=>fs.writeFile(path.join(dir,name),JSON.stringify(data));
await write('shixiseng_A_全国.json',{task_id:task.id,list:[{uuid:'1'},{uuid:'2'},{uuid:'3'}],details:{1:{ok:true},2:{ok:false}}});
await write('shixiseng_B_全国.json',{task_id:task.id,list:[{uuid:'1'},{uuid:'4'}],details:{1:{ok:true}}});
await write('shixiseng_foreign_全国.json',{task_id:'other-task',list:[{uuid:'5'}]});
await write('jobonline_A_全国.json',{task_id:task.id,records:[{job_id:'1'}]});
await write('iguopin_A_北京.json',{task_id:task.id,city:{name:'北京'},records:[{job_id:1,district_list:[{area_cn:'北京'}]},{job_id:2,district_list:[{area_cn:'上海'}]}]});
let live=await liveCollectionMetrics(task);
assert.equal(live.publicRows,6); // 4 shixiseng + 1 jobonline + 1 iguopin
assert.equal(live.details[0].processed,2);
assert.equal(live.details[0].successful,1);
assert.equal(live.details[0].failed,1);
await fs.writeFile(path.join(outputDir,'任务归属.json'),JSON.stringify({task_id:task.id}));
await fs.writeFile(path.join(outputDir,'shixiseng_标准化数据.csv'),'platform,job_id\n实习僧,1\n实习僧,6');
live=await liveCollectionMetrics(task);
assert.equal(live.publicRows,7); // CSV/checkpoint overlap not doubled
const snapshot={updatedAt:new Date().toISOString(),tasks:{[task.id]:live}};
const merged=mergeLiveProgress([task],snapshot)[0];
assert.equal(merged.metrics.candidates,7);
assert.equal(merged.metrics.hasFinalResult,false);
assert.equal(collectionProgress(merged).label,'候选采集进度');
assert.equal(collectionProgress({...merged,metrics:{...merged.metrics,hasFinalResult:true,finalRows:2000}}).percent,10);
assert.equal(mergeLiveProgress([task],{...snapshot,updatedAt:'2000-01-01'})[0].metrics.candidates,0);
assert.equal(mergeLiveProgress([task],{...snapshot,tasks:{[task.id]:{...live,task_id:'wrong'}}})[0].metrics.candidates,0);
assert.equal(mergeLiveProgress([{...task,status:'paused'}],snapshot)[0].metrics.candidates,7);
await write('shixiseng_A_全国.json',{task_id:task.id,list:[{uuid:'1'},{uuid:'2'},{uuid:'3'}],details:{1:{ok:true},2:{ok:true},3:{ok:true}}});
live=await liveCollectionMetrics(task);
assert.equal(live.details.find(row=>row.keyword==='').successful>=1,true);
assert.equal(live.details.reduce((sum,row)=>sum+row.successful,0),4);
console.log('PASS: live counts, task isolation, successful vs failed details, source/keyword dedup, freshness and final delivery separation');
console.log(`Test fixtures: ${outputDir}`);
