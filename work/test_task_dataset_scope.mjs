import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {ownedReport,isolatedDirectory,isolateLegacyTask} from './task_dataset_scope.mjs';
import {taskInsightSource} from './task-insight-source.mjs';
import {writeJsonAtomic,writeAtomic} from './collector_storage.mjs';
const base=await fs.mkdtemp(path.join(os.tmpdir(),'task-scope-test-'));
const profilePath=path.join(base,'profile.json');
await writeJsonAtomic(profilePath,{label:'智能体开发',keywords:['智能体开发'],relevance:{exclude_terms:['销售']}});
const old=path.join(base,'数据质量报告.json');
await writeJsonAtomic(old,{dataset_label:'ai漫剧师',output_rows:3150});
const original=await fs.readFile(old,'utf8');
const task={id:'scope-one',label:'智能体开发',outputDir:base,profilePath};
assert.equal(ownedReport(JSON.parse(original),task),false);
assert.equal(ownedReport({task_id:'different',dataset_label:task.label},task),false);
assert.equal(ownedReport({task_id:task.id,output_rows:0},task),true);
assert.notEqual(isolatedDirectory(base,'scope-one'),isolatedDirectory(base,'scope-two'));
assert.throws(()=>isolatedDirectory(base,'../escape'));
assert.equal(await isolateLegacyTask(task),true);
assert.equal(await isolateLegacyTask(task),false);
assert.equal(await fs.readFile(old,'utf8'),original);
await assert.rejects(()=>taskInsightSource(task),/尚未生成/);
// Four inputs: one duplicate, one invalid key; unrelated "销售" must survive.
await writeAtomic(path.join(task.outputDir,'zhaopin_标准化数据.csv'),'platform,job_id,job_name,query_keyword\n智联招聘,a,智能体开发,智能体开发\n智联招聘,b,销售,其他\n智联招聘,a,重复,智能体开发\n智联招聘,,无ID,智能体开发\n');
// A previous named delivery must never be rediscovered as a raw source.
await writeAtomic(path.join(task.outputDir,'别的岗位_3150条_标准化数据.csv'),'platform,job_id,job_name\n其他,x,不应混入\n');
const run=()=>execFileSync(process.env.TEST_PYTHON||'python',['work/finalize_configurable_dataset.py',task.outputDir,profilePath,'1'],{encoding:'utf8'});
run();
const quality=JSON.parse(await fs.readFile(path.join(task.outputDir,'数据质量报告.json'),'utf8'));
assert.equal(quality.task_id,task.id);assert.equal(quality.output_rows,2);
assert.equal(quality.input_rows,4);assert.equal(quality.duplicates_removed,1);
assert.equal(quality.missing_dedupe_key_removed,1);assert.equal(quality.low_relevance_rows_excluded,0);
const rows=JSON.parse(await fs.readFile(path.join(task.outputDir,'最终合并数据.json'),'utf8'));
assert.ok(rows.some(r=>r.job_name==='销售'));assert.ok(rows.every(r=>r.task_id===task.id));
assert.equal((await taskInsightSource(task)).taskId,task.id);
run();assert.equal(JSON.parse(await fs.readFile(path.join(task.outputDir,'数据质量报告.json'),'utf8')).input_rows,4);
assert.equal(await fs.readFile(old,'utf8'),original);
console.log(JSON.stringify({ok:true,checks:['cross-task and same-label report rejected','valid zero accepted','isolated paths','migration idempotent and history preserved','unrelated jobs retained','no target truncation','dedupe and invalid key removal','repeated merge does not absorb old deliveries','insight ownership'],base}));
