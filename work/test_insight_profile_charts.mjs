import assert from 'node:assert/strict';
import {distribution,renderDonut,renderProfileCloud,salaryExperienceGroups,renderSalaryExperienceLine,skillSalaryAssociations,renderSkillSalaryAssociations} from '../job_collector_ui/public/insight-profile-charts.js';
const rows=[...Array.from({length:6},()=>({city:'北京市',education:'本科',experience:'1-3年',salary_midpoint_k:10})),...Array.from({length:5},()=>({city:'上海',education:'硕士',experience:'5-10年',salary_midpoint_k:20})),{city:'',education:'',experience:'3-5年',salary_midpoint_k:200},{experience:'经验不限',salary_midpoint_k:300}];
assert.equal(distribution(rows,'city').reduce((sum,row)=>sum+row.count,0),rows.length);
assert.equal(distribution(rows,'city').find(row=>row.name==='北京').count,6);
assert.match(renderDonut(rows,'city','城市占比'),/未明确/);
assert.match(renderDonut(rows,'education','学历占比'),/stroke-dasharray/);
assert.match(renderDonut([],'city','城市占比'),/没有岗位样本/);
const groups=salaryExperienceGroups(rows);
assert.equal(groups.find(row=>row.name==='1-3年').median,10);
assert.equal(groups.find(row=>row.name==='经验不限').count,0);
const line=renderSalaryExperienceLine(rows);
assert.match(line,/10K/);assert.match(line,/20K/);assert.doesNotMatch(line,/200K/);
assert.equal((line.match(/<polyline/g)||[]).length,2); // Missing small cohort breaks line.
assert.match(line,/样本不足5条/);
const cloud=renderProfileCloud([{name:'Python',count:12,rate:.6},{name:'RAG',count:2,rate:.1}],'技能词云');
assert.match(cloud,/12 条岗位/);assert.match(cloud,/60.0%/);assert.doesNotMatch(cloud,/种子岗位|学习权重/);
assert.match(renderProfileCloud([{name:'软件',share:.5}],'行业词云',true),/50.0%/);
assert.match(renderProfileCloud([],'词云'),/暂无/);
const many=Array.from({length:12},(_,i)=>({city:`城市${i}`}));
assert.equal(distribution(many,'city').length,7);assert.equal(distribution(many,'city').at(-1).count,6);
assert.doesNotMatch(renderDonut([{city:'<script>'}],'city','城市'),/<script>/);
const tagged=[...Array.from({length:5},()=>({skills:['Python','Python'],salary_midpoint_k:20})),...Array.from({length:5},()=>({skills:[],salary_midpoint_k:10}))];
assert.equal(skillSalaryAssociations(tagged)[0].difference,10);
assert.equal(skillSalaryAssociations(tagged)[0].tagged.count,5);
assert.match(renderSkillSalaryAssociations(tagged),/至少需要80条/);
assert.equal(skillSalaryAssociations(tagged.slice(0,9))[0].difference,null);
assert.match(renderSkillSalaryAssociations([]),/至少需要80条/);
console.log('PASS: weighted cohort clouds, complete donut denominators, other/unknown groups, salary cleaning, experience order, sparse line gaps, safe labels');
