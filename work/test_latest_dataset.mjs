import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {updateUnifiedDataset} from './unified_collection_store.mjs';
import {taskInsightSource} from './task-insight-source.mjs';
import {exportLatestDataset,buildLatestWorkbook,excelSafeText} from './export_latest_dataset.mjs';
import {readJobDataset} from './job_dataset.mjs';
const directory=await fs.mkdtemp(path.join(os.tmpdir(),'latest-export-'));
assert.equal(excelSafeText('岗位\u0003描述'),'岗位描述');
assert.equal(excelSafeText('=HYPERLINK("x")'),'\'=HYPERLINK("x")');
const task={id:'fixture',label:'嵌入式软件开发',outputDir:directory,status:'paused',datasetScopeVersion:2};
await fs.writeFile(path.join(directory,'任务归属.json'),JSON.stringify({task_id:task.id}));
const source=path.join(directory,'zhaopin_标准化数据.csv');
await fs.writeFile(source,'platform,job_id,job_name,company_name,city,salary,job_description\n智联,1,嵌入式软件工程师,示例公司,深圳,15-25K,"C/C++ STM32\n驱动开发"\n智联,1,嵌入式软件工程师,示例公司,深圳,15-25K,"C/C++ STM32\n驱动开发"');
assert.equal((await updateUnifiedDataset(task,{publishCsv:true})).rows,1);
const initial=await taskInsightSource(task);
assert.equal(initial.dataset.resolution,'latest_snapshot');assert.equal(initial.dataset.expectedRows,1);assert.equal(initial.dataset.complete,false);
assert.equal((await readJobDataset(initial.dataset.path)).rows[0]['岗位名称'],'嵌入式软件工程师');
let result=await exportLatestDataset(task,{resources:async()=>{throw Error('内存不足');}});
assert.equal(result.status,'partial');assert.match(result.warning,/CSV已更新/);assert.equal(task.status,'paused');
await fs.appendFile(source,'\n智联,2,嵌入式Linux工程师,另一公司,北京,20-30K,开发Linux内核驱动');
result=await exportLatestDataset(task,{resources:async()=>{},build:async(content,out)=>buildLatestWorkbook(content,out,process.env.LATEST_EXPORT_PREVIEW==='1'?{previewPath:path.join(directory,'preview.png')}:{})});
assert.equal(result.status,'completed');assert.equal(result.rows,2);assert.equal((await taskInsightSource(task)).dataset.path,initial.dataset.path);
const workbook=await readJobDataset(path.join(directory,'最新数据.xlsx'));
assert.equal(workbook.rows.length,2);assert.equal(workbook.rows[0]['岗位ID'],'1');
const preserved=await fs.readFile(path.join(directory,'最新数据.xlsx'));
result=await exportLatestDataset(task,{resources:async()=>{},build:async()=>{throw Error('文件占用');}});
assert.equal(result.status,'partial');assert.deepEqual(await fs.readFile(path.join(directory,'最新数据.xlsx')),preserved);
await assert.rejects(taskInsightSource({...task,id:'foreign'}),/归属/);
await fs.appendFile(initial.dataset.path,'tampered');await assert.rejects(taskInsightSource(task),/正在更新/);
console.log(JSON.stringify({pass:true,checks:'dedup, paused export, latest-source, overwrite, XLSX roundtrip, low-resource fallback, preserve old workbook, isolation, hash validation',directory}));
