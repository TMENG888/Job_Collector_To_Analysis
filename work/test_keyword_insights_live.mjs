import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {chromium} from 'playwright';
const origin='http://127.0.0.1:8765';
const response=await (await fetch(origin+'/api/insights')).json();
assert.equal(response.status,'completed',response.message);
const report=JSON.parse(await fs.readFile('ui_data/insights/岗位市场洞察.json','utf8'));
assert.equal(report.total_rows,3150);
assert.equal(report.sample_rows,229);
assert.equal(report.cohort_observations.length,229);
assert.equal(report.keyword_selection.algorithm,'区分性对数优势比关键词');
assert.equal(report.keyword_selection.reviewed_rows,120);
assert.equal(report.keyword_selection.uncertain_rows,7);
const expected=JSON.parse(await fs.readFile('ui_data/keyword_validation/ai_drama_v1/全量筛选结果.json','utf8'));
const ids=expected.rows.filter(x=>x.matched).map(x=>x.row_no).sort((a,b)=>a-b);
assert.deepEqual(report.cohort_observations.map(x=>x.row_no).sort((a,b)=>a-b),ids);
const sourceHash=crypto.createHash('sha256').update(await fs.readFile(report.input_file)).digest('hex');
assert.equal(sourceHash,expected.source_sha256,'原始Excel不得变更');
const browser=await chromium.launch({headless:true,executablePath:'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/api/**',route=>route.request().method()==='GET'?route.continue():route.abort());
  await page.goto(origin+'/insights');
  await page.waitForFunction(()=>document.querySelector('#insightFilterAudit')?.textContent.includes('区分性对数优势比关键词'));
  const audit=await page.locator('#insightFilterAudit').textContent();
  assert.match(audit,/229/);assert.match(audit,/40 条/);assert.match(audit,/非人工专家金标准/);assert.match(audit,/待定 7 条/);
  assert.equal(await page.locator('.insight-kpis .stat strong').first().textContent(),'229');
  await page.locator('#insightFilterAudit').screenshot({path:'ui_data/keyword_validation/ai_drama_v1/页面验证.png'});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,rows:3150,included:229,salary_rows:report.quality.salary_rows,sourceUnchanged:true,uiRendered:true,pageErrors:errors}));
} finally {await browser.close();}
